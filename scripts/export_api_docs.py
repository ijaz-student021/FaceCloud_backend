"""Export the OpenAPI document and a readable endpoint reference from the code.

    python scripts/export_api_docs.py            # writes docs/api/openapi.yaml and docs/api/API_REFERENCE.md

Both are generated from the same schema Swagger UI serves at /api/docs/, so they cannot drift from the code; re-run after changing an
endpoint. ``config/test_api_docs.py`` fails when an operation lacks text.
"""
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings")

METHODS = ("get", "post", "put", "patch", "delete")


def main():
    import django
    import yaml

    django.setup()
    from drf_spectacular.generators import SchemaGenerator

    schema = SchemaGenerator().get_schema(request=None, public=True)
    out = ROOT / "docs" / "api"
    out.mkdir(parents=True, exist_ok=True)
    (out / "openapi.yaml").write_text(yaml.safe_dump(schema, sort_keys=False, allow_unicode=True, width=120))

    components = schema.get("components", {}).get("schemas", {})

    def resolve(node):
        return components.get(node["$ref"].split("/")[-1], {}) if "$ref" in node else node

    def request_fields(operation):
        content = operation.get("requestBody", {}).get("content", {})
        for body in content.values():
            node = resolve(body.get("schema", {}))
            required = set(node.get("required", []))
            fields = {name: prop for name, prop in node.get("properties", {}).items() if not resolve(prop).get("readOnly") and not prop.get("readOnly")}
            return ", ".join(f"`{name}`{'*' if name in required else ''}" for name in fields) or "-"
        return "-"

    tags = {tag["name"]: tag["description"] for tag in schema.get("tags", [])}
    grouped = {}
    for path, item in schema["paths"].items():
        for method, operation in item.items():
            if method in METHODS:
                grouped.setdefault((operation.get("tags") or ["other"])[0], []).append((path, method, operation))

    lines = ["# FaceCloud API reference", "",
             f"Generated by `scripts/export_api_docs.py` from the OpenAPI schema ({sum(len(v) for v in grouped.values())} operations). "
             "Interactive version: `/api/docs/` (Swagger UI) and `/api/redoc/`; machine-readable: `docs/api/openapi.yaml`. "
             "`*` marks a required request field. Every endpoint except those marked public needs `Authorization: Bearer <access token>`.", "",
             schema["info"]["description"].strip(), ""]
    for tag in sorted(grouped):
        lines += [f"## {tag}", "", tags.get(tag, ""), "", "| Method | Path | What it does | Request fields | Success |", "|---|---|---|---|---|"]
        for path, method, operation in sorted(grouped[tag], key=lambda row: (row[0], METHODS.index(row[1]))):
            success = ", ".join(code for code in operation["responses"] if code.startswith("2")) or "-"
            public = " (public)" if operation.get("security") and not all(operation["security"]) else ""
            lines.append(f"| {method.upper()} | `{path}` | {operation['summary']}{public} | {request_fields(operation)} | {success} |")
        lines.append("")
    (out / "API_REFERENCE.md").write_text("\n".join(lines))
    print(f"{sum(len(v) for v in grouped.values())} operations in {len(grouped)} groups -> {out}")


if __name__ == "__main__":
    main()
